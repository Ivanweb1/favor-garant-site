#   service-*.html   — страница услуги (образец: лазерная резка латуни),
#   expertise-*.html — шесть видов экспертизы (тексты со старого сайта /expertise/...),
#   expertise.html   — хаб раздела «Экспертиза»,
#   portfolio.html   — «Наши работы» сеткой с фильтром.
#   team / reviews / certificates / guarantees.html — страницы компании (данные из about.html).
# Шапка, заявка и подвал берутся из site/services.html — правки шапки/подвала вносить туда (и в остальные страницы), потом перезапускать.
# Запуск: python tools/build_text_pages.py
import re
from pathlib import Path

from PIL import Image

SITE = Path(__file__).resolve().parent.parent / 'site'

NBSP_WORDS = re.compile(r'(?<=[\s>(«—])([а-яА-ЯёЁ]{1,2}|[А-Я]{2,3}) (?=[^\s<])')


def nbsp(text):
    """Неразрывный пробел после коротких слов — как в остальных текстах сайта (только в тексте, не в тегах)."""
    parts = re.split(r'(<[^>]+>)', text)
    return ''.join(p if p.startswith('<') else NBSP_WORDS.sub(r'\1&nbsp;', ' ' + p)[1:] for p in parts)


def size(src):
    with Image.open(SITE / src) as im:
        return im.size


def img(src, alt, lazy=True, cls=''):
    w, h = size(src)
    c = f' class="{cls}"' if cls else ''
    lz = ' loading="lazy"' if lazy else ''
    return f'<img{c} src="{src}" alt="{alt}"{lz} width="{w}" height="{h}">'


def checks(items):
    return '<ul class="checks">' + ''.join(f'<li>{i}</li>' for i in items) + '</ul>'


def points(items):
    out = []
    for it in items:
        b, s = it if isinstance(it, tuple) else (it, '')
        out.append(f'<div class="doc__point"><b>{b}</b>' + (f'<span>{s}</span>' if s else '') + '</div>')
    return '<div class="doc__points">' + ''.join(out) + '</div>'


def note(t):
    return f'<p class="article__note">{t}</p>'


# ---------- оболочка из services.html ----------

shell = (SITE / 'services.html').read_text(encoding='utf-8')
HEAD = shell[:shell.index('<main>') + len('<main>\n')]
TAIL = shell[shell.index('  <!-- 8. Заявка -->'):]
TITLE_RE = re.compile(r'<title>[^<]*</title>')
DESC_RE = re.compile(r'<meta name="description" content="[^"]*">')


def page_head(title, desc, current):
    h = TITLE_RE.sub(f'<title>{title} — ФАВОР-ГАРАНТ</title>', HEAD)
    h = DESC_RE.sub(f'<meta name="description" content="{desc}">', h)
    h = h.replace(' aria-current="page"', '')
    if current:
        h = h.replace(f'class="nav__link" href="{current}">', f'class="nav__link" href="{current}" aria-current="page">', 1)
    return h


def page_tail(light, product=True):
    t = TAIL
    if not light:
        t = t.replace('<section class="section section--light" id="request">', '<section class="section" id="request">', 1)
    if not product:
        t = t.replace('<option selected>', '<option>', 1)
    return t


def crumbs(items):
    lis = ''.join(f'<li><a href="{href}">{nbsp(name)}</a></li>' for name, href in items[:-1])
    return f'<ol class="crumbs" aria-label="Навигация по сайту">{lis}<li><span aria-current="page">{nbsp(items[-1][0])}</span></li></ol>'


def write(name, html):
    (SITE / name).write_text(html, encoding='utf-8', newline='')
    print('ok', name)


# ---------- шаблон текстовой страницы ----------

def siblings_block(sib, current, bg):
    first, second, items = sib
    tiles = []
    for label, href, *icon in items:
        ic = f'<img class="sibling__icon" src="img/icons/{icon[0]}.svg" alt="" width="40" height="40" loading="lazy">' if icon else ''
        text = f'{ic}<span class="sibling__label">{nbsp(label)}</span>'
        if label == current:
            tiles.append(f'<span class="sibling" aria-current="page">{text}</span>')
        else:  # страницы ещё нет — плитка активная, ссылка-заглушка
            tiles.append(f'<a class="sibling" href="{href or "#"}">{text}</a>')
    return f'''  <section class="section{bg}" id="related">
    <div class="container">
      <div class="page-head">
        <h2 class="h2 duo duo--inline">
          <span>{nbsp(first)}</span>
          <span class="duo__second">{nbsp(second)}</span>
        </h2>
      </div>
      <div class="siblings">
        {"".join(tiles)}
      </div>
    </div>
  </section>

'''


def text_page(p):
    first, second = p['h1']
    w, h = size(p['photo'][0])
    keyfacts = ''
    if p.get('keyfacts'):
        cells = ''.join(f'<div><dt>{nbsp(dt)}</dt><dd>{dd}</dd></div>' for dt, dd in p['keyfacts'])
        keyfacts = f'\n      <dl class="keyfacts" style="--cols: {len(p["keyfacts"])}">{cells}</dl>'
    toc = ''.join(f'<a href="#{sid}">{nbsp(t)}</a>' for sid, t, _ in p['sections'])
    body = '\n'.join(f'<section id="{sid}">\n<h2>{nbsp(t)}</h2>\n{nbsp(html.strip())}\n</section>' for sid, t, html in p['sections'])
    cta_title, cta_text, cta_btn = p['cta']

    blocks = []  # секции после текста, фон чередуется: текст белый, дальше светлый, белый...
    if p.get('faq'):
        items = ''.join(f'''
        <details class="faq__item">
          <summary class="faq__q">{nbsp(q)}</summary>
          <p class="faq__a">{nbsp(a)}</p>
        </details>''' for q, a in p['faq'])
        blocks.append(lambda bg: f'''  <section class="section{bg}" id="faq">
    <div class="container">
      <div class="page-head">
        <h2 class="h2 duo duo--inline">
          <span>Вопросы</span>
          <span class="duo__second">и&nbsp;ответы</span>
        </h2>
      </div>
      <div class="faq">{items}
      </div>
    </div>
  </section>

''')
    if p.get('siblings'):
        blocks.append(lambda bg: siblings_block(p['siblings'], p['crumbs'][-1][0], bg))

    after = ''
    light = True
    for b in blocks:
        after += b(' section--light' if light else '')
        light = not light

    main = f'''  <!-- Текстовая страница: собрано tools/build_text_pages.py — правки вносить в скрипт -->
  <section class="section section--light page-top">
    <div class="container">
      {crumbs(p['crumbs'])}
      <div class="lead-hero">
        <div class="lead-hero__body">
          <p class="eyebrow">{p['eyebrow']}</p>
          <h1 class="lead-hero__title duo">
            <span>{nbsp(first)}</span>
            <span class="duo__second">{nbsp(second)}</span>
          </h1>
          <p class="lead-hero__text">{nbsp(p['lead'])}</p>
          <div class="lead-hero__actions">
            <a class="btn btn--primary" href="#request-form">{p['button']}</a>
            <a class="link-arrow" href="tel:+78003332227">8 (800) 333-222-7</a>
          </div>
        </div>
        <div class="lead-hero__media"><img src="{p['photo'][0]}" alt="{p['photo'][1]}" width="{w}" height="{h}"></div>
      </div>{keyfacts}
    </div>
  </section>

  <section class="section" id="content">
    <div class="container doc">
      <aside class="doc__aside">
        <nav class="toc" aria-label="Содержание страницы">
          <p class="toc__title">Содержание</p>
          {toc}
        </nav>
        <div class="doc__cta">
          <p class="doc__cta-title">{nbsp(cta_title)}</p>
          <p class="doc__cta-text">{nbsp(cta_text)}</p>
          <a class="doc__cta-phone" href="tel:+78003332227">8 (800) 333-222-7</a>
          <a class="btn btn--light" href="#request-form">{cta_btn}</a>
        </div>
      </aside>
      <div class="article__body">
{body}
      </div>
    </div>
  </section>

{after}'''
    write(p['file'], page_head(p['title'], p['desc'], p.get('nav', 'services.html')) + '\n' + main + page_tail(light))


